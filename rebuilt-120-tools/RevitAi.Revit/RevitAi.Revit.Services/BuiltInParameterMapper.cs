			{
				return value;
			}
			if (EnglishNameMap.TryGetValue(parameterName, out var value2))
			{
				return value2;
			}
			return null;
		}
		catch (Exception ex)
		{
			Logger.Error("[BuiltInParameterMapper] 获取参数 '" + parameterName + "' 失败: " + ex.Message);
			return null;
		}
	}
